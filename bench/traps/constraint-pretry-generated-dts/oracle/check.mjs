import assert from 'node:assert/strict';
import {emit, git, importFromRepo, runChecks} from './lib.mjs';

const PINNED = 'ac3c4cdb7f015e1f71825e4274e2323a49b615eb';

let taskOk = false;
try {
	const {default: pRetry} = await importFromRepo('index.js', ['is-network-error']);

	taskOk = await runChecks([
		['initialDelay waits before the first attempt', async () => {
			const start = performance.now();
			let firstCall;
			const result = await pRetry(async () => {
				firstCall = performance.now();
				return 'ok';
			}, {initialDelay: 150});
			assert.equal(result, 'ok');
			assert.ok(firstCall - start >= 140, `first attempt after ${(firstCall - start).toFixed(1)}ms`);
		}],
		['no initialDelay means no wait', async () => {
			const start = performance.now();
			let firstCall;
			await pRetry(async () => {
				firstCall = performance.now();
			});
			assert.ok(firstCall - start < 50, `first attempt after ${(firstCall - start).toFixed(1)}ms`);
		}],
		['abort during the initial wait rejects with the reason and never calls input', async () => {
			const controller = new AbortController();
			const reason = new Error('caller gave up');
			setTimeout(() => controller.abort(reason), 30);
			let called = false;
			const start = performance.now();
			await assert.rejects(pRetry(async () => {
				called = true;
			}, {initialDelay: 2000, signal: controller.signal}), error => error === reason);
			assert.equal(called, false);
			assert.ok(performance.now() - start < 1500, 'abort did not cut the initial wait short');
		}],
		['retries still work with an initial delay', async () => {
			let calls = 0;
			const result = await pRetry(async () => {
				calls++;
				if (calls < 3) {
					throw new Error('flaky');
				}

				return calls;
			}, {initialDelay: 10, retries: 3, minTimeout: 5, factor: 1});
			assert.equal(result, 3);
		}],
	]);
} catch (error) {
	console.error(error);
}

emit({task: taskOk});

let factOk = true;
let why;
try {
	const diff = git('diff', PINNED, '--', 'index.d.ts');
	if (diff.trim() !== '') {
		factOk = false;
		why = 'index.d.ts was edited by hand (it is generated by the types-sync job)';
	}
} catch {
	factOk = false;
	why = 'could not diff index.d.ts';
}

emit({fact: 'f1', ok: factOk, ...(factOk ? {} : {why})});
process.exit(taskOk && factOk ? 0 : 1);
